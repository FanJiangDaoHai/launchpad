    public class LargeComponentTests
    {
        [SetUp]
        public void Setup()
        {
            ComponentTypeIndex.Reset();
        }

        [Test]
        public void Entity_Can_Have_Component_Index_64()
        {
            // C64 应该是第65个组件，索引为64（0-based），超出单个ulong的范围
            var context = new Context("Large");
            var entity = context.CreateEntity();

            entity.AddComponent(new C64 { V = 999 });

            Assert.IsTrue(entity.HasComponent<C64>());
            Assert.AreEqual(999, entity.GetComponent<C64>().V);
        }

        [Test]
        public void Entity_Can_Have_Many_Components_Over_64()
        {
            var context = new Context("Large");
            var entity = context.CreateEntity();

            // 添加从 C00 到 C64 的所有组件
            entity.AddComponent(new C00 { V = 0 });
            entity.AddComponent(new C01 { V = 1 });
            entity.AddComponent(new C02 { V = 2 });
            entity.AddComponent(new C63 { V = 63 });
            entity.AddComponent(new C64 { V = 64 });

            Assert.AreEqual(5, entity.ComponentCount);
            Assert.IsTrue(entity.HasComponent<C00>());
            Assert.IsTrue(entity.HasComponent<C01>());
            Assert.IsTrue(entity.HasComponent<C02>());
            Assert.IsTrue(entity.HasComponent<C63>());
            Assert.IsTrue(entity.HasComponent<C64>());
            Assert.IsFalse(entity.HasComponent<C03>());

            var indices = entity.GetComponentIndices();
            Assert.AreEqual(5, indices.Length);
            Assert.Contains(ComponentTypeIndex<C64>.Index, indices);
        }

        [Test]
        public void Matcher_Matches_Entity_With_Component_Over_64()
        {
            var context = new Context("Large");
            var matcher = Matcher.AllOf(ComponentTypeIndex<C64>.Index);
            var group = context.GetGroup(matcher);

            var entity = context.CreateEntity();
            entity.AddComponent(new C64 { V = 100 });

            Assert.AreEqual(1, group.Count);
            Assert.AreSame(entity, group.GetSingleEntity());
        }

        [Test]
        public void Context_Can_Manage_128_Component_Types()
        {
            var context = new Context("Large");

            var e1 = context.CreateEntity();
            e1.AddComponent(new C00 { V = 0 });
            e1.AddComponent(new C32 { V = 32 });
            e1.AddComponent(new C64 { V = 64 });
            e1.AddComponent(new C96 { V = 96 });

            var e2 = context.CreateEntity();
            e2.AddComponent(new C64 { V = 640 });
            e2.AddComponent(new C96 { V = 960 });

            var group = context.GetGroup(Matcher.AllOf(
                ComponentTypeIndex<C64>.Index,
                ComponentTypeIndex<C96>.Index
            ));

            Assert.AreEqual(2, group.Count);
        }

        [Test]
        public void Entity_RemoveComponent_Over_64()
        {
            var context = new Context("Large");
            var entity = context.CreateEntity();

            entity.AddComponent(new C64 { V = 1 });
            Assert.IsTrue(entity.HasComponent<C64>());

            entity.RemoveComponent<C64>();
            Assert.IsFalse(entity.HasComponent<C64>());
            Assert.AreEqual(0, entity.ComponentCount);
        }

        [Test]
        public void Entity_ReplaceComponent_Over_64()
        {
            var context = new Context("Large");
            var entity = context.CreateEntity();

            entity.AddComponent(new C64 { V = 1 });
            entity.ReplaceComponent(new C64 { V = 2 });

            Assert.AreEqual(2, entity.GetComponent<C64>().V);
        }

        [Test]
        public void Stress_Many_Component_Types()
        {
            var context = new Context("Stress");
            var entity = context.CreateEntity();

            // 添加大量组件，覆盖多个ulong
            entity.AddComponent(new C00 { V = 0 });
            entity.AddComponent(new C31 { V = 31 });
            entity.AddComponent(new C32 { V = 32 });
            entity.AddComponent(new C63 { V = 63 });
            entity.AddComponent(new C64 { V = 64 });
            entity.AddComponent(new C95 { V = 95 });
            entity.AddComponent(new C96 { V = 96 });
            entity.AddComponent(new C127 { V = 127 });

            Assert.AreEqual(8, entity.ComponentCount);

            var indices = entity.GetComponentIndices();
            Assert.AreEqual(8, indices.Length);
        }
